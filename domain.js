export function dayKey(zone = "UTC", date = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: zone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
}
export function shiftDay(value, days) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return "";
  const d = new Date(value + "T12:00:00Z");
  if (isNaN(d)) return "";
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}
export function localToday(zone) {
  return dayKey(
    zone || Intl.DateTimeFormat().resolvedOptions().timeZone || "UTC",
  );
}
export function birthLimit(zone) {
  return shiftDay(localToday(zone), -1);
}
export function validDate(value, today = localToday()) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const d = new Date(value + "T12:00:00Z");
  return (
    !isNaN(d) &&
    d.toISOString().slice(0, 10) === value &&
    value >= "1900-01-01" &&
    value <= today
  );
}
