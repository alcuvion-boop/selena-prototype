export function numerology(value) {
  if (!validDate(value)) throw new Error("Проверь дату рождения.");
  const digits = value.replaceAll("-", "").split("").map(Number);
  let n = digits.reduce((a, b) => a + b, 0);
  const chain = [digits.join(" + ") + " = " + n];
  while (n > 9) {
    const ds = String(n).split("").map(Number);
    const next = ds.reduce((a, b) => a + b, 0);
    chain.push(ds.join(" + ") + " = " + next);
    n = next;
  }
  return { number: n, chain };
}
export function hash(s) {
  return [...s].reduce((a, c) => (Math.imul(a, 31) + c.charCodeAt(0)) >>> 0, 7);
}
export function dailyIndex(key, seed) {
  return hash(key + "|" + seed) % cards.length;
}
export function drawCards(count = 3) {
  const available = cards.map((_, i) => i);
  const out = [];
  for (let i = 0; i < count; i++) {
    const v = new Uint32Array(1);
    crypto.getRandomValues(v);
    const limit = Math.floor(4294967296 / available.length) * available.length;
    while (v[0] >= limit) crypto.getRandomValues(v);
    out.push(available.splice(v[0] % available.length, 1)[0]);
  }
  return out;
}
